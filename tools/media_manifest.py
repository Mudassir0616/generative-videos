"""Write docs/MEDIA.md: an inventory of every git-ignored file in the workspace (size, duration, sha256).

The media is not in the repo (see .gitignore), so this file is how a fresh clone (or a new agent) knows what
existed, where it lived, and can verify copies restored from Drive/backup. Re-run after adding or rendering media:
    python tools/media_manifest.py
Needs git and (for durations) ffprobe on PATH.
"""
import hashlib
import pathlib
import shutil
import subprocess
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parents[1]
MEDIA = {".mp4", ".mov", ".mp3", ".wav", ".m4a", ".aac"}

files = subprocess.run(["git", "ls-files", "--others", "--ignored", "--exclude-standard", "-z"], cwd=ROOT,
                       capture_output=True, text=True, encoding="utf-8").stdout.split("\0")
files = sorted(f for f in files if f and (ROOT / f).is_file())
has_probe = shutil.which("ffprobe") is not None


def duration(p):
    if not has_probe or p.suffix.lower() not in MEDIA:
        return ""
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)],
                         capture_output=True, text=True).stdout.strip()
    try:
        return f"{float(out):.2f} s"
    except ValueError:
        return ""


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:16]


NOISE = (".hyperframes/", "__pycache__/", "node_modules/")
noise = [f for f in files if any(n in f for n in NOISE)]
groups = defaultdict(list)
for f in files:
    if f in noise:
        continue
    parts = f.split("/")
    if "frames" in parts:                      # e.g. refrences/<lib>/<reel>/frames/*.jpg -> one summary row per frames dir
        groups["/".join(parts[:parts.index("frames") + 1])].append(f)
    else:
        groups["/".join(parts[:2]) if len(parts) > 2 else parts[0]].append(f)

lines = ["# Media inventory (not in git)", "",
         "Generated by `python tools/media_manifest.py`. These files are git-ignored (see `.gitignore`); they live only on",
         "the working machine (Mudassir's PC) and in whatever backup the team uses. A fresh clone has none of them:",
         "ask the user for the files, then check them against the sha256 prefixes below. How each was made: `docs/HISTORY.md`.",
         "Small media folders (frames/, .hyperframes/ snapshots) are summarised by count instead of listed per file.", ""]
total = 0
for g in sorted(groups):
    fs = groups[g]
    size = sum((ROOT / f).stat().st_size for f in fs)
    total += size
    lines.append(f"## {g}  ({len(fs)} files, {size / 1048576:.1f} MB)")
    if g.endswith("/frames"):
        lines += ["", f"{len(fs)} extracted frames (cut_NN_*.jpg, sec_NNN.jpg); regenerable from the reel's video.mp4 with tools/prep_reels.py.", ""]
        continue
    lines += ["", "| File | Size | Duration | sha256 (16) |", "|---|---|---|---|"]
    for f in fs:
        p = ROOT / f
        lines.append(f"| `{f}` | {p.stat().st_size / 1048576:.1f} MB | {duration(p)} | `{sha(p)}` |")
    lines.append("")
nz = sum((ROOT / f).stat().st_size for f in noise)
lines.append(f"## Local tool state (not listed)\n\n{len(noise)} files, {nz / 1048576:.1f} MB in .hyperframes/ "
             "(snapshots, check reports), __pycache__/ and similar. Safe to delete.\n")
lines.insert(6, f"**Total ignored: {len(files)} files, {(total + nz) / 1048576:.0f} MB.**\n")
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "MEDIA.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"docs/MEDIA.md: {len(files)} files, {total / 1048576:.0f} MB")
