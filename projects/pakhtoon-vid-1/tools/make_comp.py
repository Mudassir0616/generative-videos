"""Write index.html (the HyperFrames overlay composition) for one version of the Pukhtoon reel.

usage: python tools/make_comp.py v1|v2      then: npm run render
v1: 15.04 s (base-v1.mp4, music-v1.wav), first food cut at frame 121
v2: 20.21 s (base-v2.mp4, music-v2.wav), first food cut at frame 172
On screen: The Caliph logo (gold emblem + white wordmark) top centre over a soft top gradient for the whole reel,
and "Welcome To Pukhtoon" in Great Vibes, written on at the start and dissolved away on the first food cut.
"""
import pathlib
import sys

V = {
    "v1": {"frames": 361, "food": 121, "base": "assets/base-v1.mp4", "music": "assets/music-v1.wav"},
    "v2": {"frames": 485, "food": 172, "base": "assets/base-v2.mp4", "music": "assets/music-v2.wav"},
}
ver = sys.argv[1]
c = V[ver]
dur = f'{c["frames"] / 24:.4f}'

html = f"""<!doctype html>
<html lang="en" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <!-- generated by tools/make_comp.py {ver}; edit the script, not this file -->
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <style>
      @font-face {{ font-family: "GreatVibes"; src: url("assets/fonts/GreatVibes-Regular.ttf") format("truetype"); font-display: block; }}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: 1080px; height: 1920px; overflow: hidden; background: #000; }}
      #root {{ position: relative; width: 1080px; height: 1920px; background: #000; }}
      .clip {{ position: absolute; inset: 0; }}
      #base {{ width: 1080px; height: 1920px; object-fit: cover; }}

      /* soft dark gradient behind the logo so the white wordmark reads over light ceilings */
      #scrim {{ position: absolute; left: 0; right: 0; top: 0; height: 760px;
                background: linear-gradient(180deg, rgba(18, 10, 3, 0.62) 0%, rgba(18, 10, 3, 0.42) 40%, rgba(18, 10, 3, 0) 100%); }}
      /* The Caliph logo: gold emblem + white wordmark, static top centre (static keeps the loop seamless) */
      #logo {{ position: absolute; left: 50%; top: 120px; width: 500px; margin-left: -250px;
               filter: drop-shadow(0 3px 10px rgba(15, 8, 2, 0.55)) drop-shadow(0 0 2px rgba(15, 8, 2, 0.4)); }}

      #welcome {{ position: absolute; left: 0; right: 0; top: 540px; text-align: center; font-family: "GreatVibes", cursive; color: #fff6e6;
                  text-shadow: 0 3px 26px rgba(30, 16, 4, 0.7), 0 0 60px rgba(30, 16, 4, 0.35), 0 1px 4px rgba(30, 16, 4, 0.55); line-height: 1; }}
      #welcome .ln {{ display: block; padding: 0.12em 0.35em 0.2em; }}
      #welcome .l1 {{ font-size: 118px; }}
      #welcome .l2 {{ font-size: 196px; margin-top: -18px; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{dur}" data-fps="24" data-width="1080" data-height="1920">
      <video id="base" class="clip" src="{c["base"]}" data-start="0" data-duration="{dur}" data-track-index="0" muted playsinline></video>

      <div id="overlay" class="clip" data-start="0" data-duration="{dur}" data-track-index="1">
        <div id="scrim"></div>
        <img id="logo" src="assets/caliph-logo-full.png" alt="The Caliph Hotels &amp; Executive Suites" />
        <div id="welcome" data-layout-allow-overflow>
          <span class="ln l1">Welcome To</span>
          <span class="ln l2">Pukhtoon</span>
        </div>
      </div>

      <audio id="music" src="{c["music"]}" data-start="0" data-duration="{dur}" data-volume="1" data-track-index="2"></audio>
    </div>

    <script>
      // first food cut: the text leaves across it
      const FOOD = {c["food"]} / 24;
      const tl = gsap.timeline({{ paused: true }});

      // write-on: each line revealed left to right out of a blur, line 2 follows line 1
      tl.fromTo("#welcome .l1", {{ clipPath: "inset(-20% 100% -20% 0%)", filter: "blur(8px)", opacity: 0.4 }},
        {{ clipPath: "inset(-20% 0% -20% 0%)", filter: "blur(0px)", opacity: 1, duration: 0.9, ease: "power2.out" }}, 0.15);
      tl.fromTo("#welcome .l2", {{ clipPath: "inset(-20% 100% -20% 0%)", filter: "blur(10px)", opacity: 0.4 }},
        {{ clipPath: "inset(-20% 0% -20% 0%)", filter: "blur(0px)", opacity: 1, duration: 1.15, ease: "power2.out" }}, 0.55);
      tl.fromTo("#welcome", {{ y: 14 }}, {{ y: 0, duration: 2.0, ease: "power2.out" }}, 0.15);
      tl.to("#welcome", {{ y: -10, duration: FOOD - 2.4, ease: "sine.inOut" }}, 2.15);
      // exit with the first food: lift, scale up slightly, dissolve through blur, finishing just after the cut
      tl.to("#welcome", {{ y: -70, scale: 1.08, filter: "blur(14px)", opacity: 0, duration: 0.42, ease: "power2.in" }}, FOOD - 0.24);

      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
"""
pathlib.Path(__file__).resolve().parents[1].joinpath("index.html").write_text(html, encoding="utf-8", newline="\n")
print(f"index.html -> {ver} ({dur} s)")
